// TypeScript declarations for a Contract file, written beside it as `<name>.d.contract.ts` (the name
// TypeScript's `allowArbitraryExtensions` looks for), so `import { Button } from './button.contract'` is
// typed and a story's args are checked against the component's props.
import { basename, dirname, join } from 'node:path';

import type { ComponentInfo, Field } from '../types.ts';
import { enumMembers, isAction } from './contract.ts';

export interface ShapeInfo {
  name: string;
  fields: Field[];
}

/** The shapes a Contract file declares. */
export function parseShapes(source: string): ShapeInfo[] {
  const shapes: ShapeInfo[] = [];
  let current: ShapeInfo | null = null;
  for (const raw of source.split(/\r?\n/)) {
    const line = raw.replace(/\s\/\/.*$/, '').replace(/^\/\/.*$/, '');
    if (!line.trim()) continue;
    if (!/^\s/.test(line)) {
      const name = /^shape\s+([A-Za-z_]\w*)/.exec(line)?.[1];
      current = name ? { name, fields: [] } : null;
      if (current) shapes.push(current);
    } else if (current) {
      const field = /^([A-Za-z_]\w*)\s*:\s*(.+)$/.exec(line.trim());
      if (field) current.fields.push({ name: field[1]!, type: field[2]!.trim() });
    }
  }
  return shapes;
}

/** A Contract type in TypeScript. A shape declared in another file is `unknown`: its fields are not in this one. */
export function tsType(type: string, shapes: ReadonlySet<string>): string {
  const t = type.trim();
  if (t.endsWith('[]')) return `Array<${tsType(t.slice(0, -2), shapes)}>`;
  if (t.startsWith('option<') && t.endsWith('>')) return `${tsType(t.slice('option<'.length, -1), shapes)} | null`;
  const members = enumMembers(t);
  if (members) return members.map((m) => JSON.stringify(m)).join(' | ') || 'string';
  if (t === 'string' || t === 'color') return 'string';
  if (t === 'number') return 'number';
  if (t === 'bool') return 'boolean';
  if (t === 'action') return '(...args: any[]) => void';
  return shapes.has(t) ? t : 'unknown';
}

/** Where a Contract file's declarations go. */
export const declarationPath = (file: string) => join(dirname(file), `${basename(file, '.contract')}.d.contract.ts`);

export function declarationFor(file: string, components: ComponentInfo[], shapes: ShapeInfo[]): string {
  const known = new Set(shapes.map((s) => s.name));
  const fields = (list: Field[]) => list.map((f) => `  ${f.name}: ${tsType(f.type, known)};`);
  const lines = [
    `// Generated by storybook-framework-exact from ${basename(file)}. Do not edit.`,
    "import type { ExactComponent } from 'storybook-framework-exact';",
    '',
  ];
  for (const shape of shapes) lines.push(`export interface ${shape.name} {`, ...fields(shape.fields), '}', '');
  for (const component of components) {
    const args = [...component.props, ...component.inject];
    const name = `${component.name}Args`;
    // An action prop is optional in a story: the Actions panel takes its calls when no arg is given.
    lines.push(
      args.length ? `export interface ${name} {` : `export interface ${name} {}`,
      ...(args.length ? [...args.map((f) => `  ${f.name}${isAction(f) ? '?' : ''}: ${tsType(f.type, known)};`), '}'] : []),
      `export declare const ${component.name}: ExactComponent<${name}>;`,
      ''
    );
  }
  lines.push(`declare const components: { ${components.map((c) => `${c.name}: typeof ${c.name}`).join('; ')} };`, 'export default components;', '');
  return lines.join('\n');
}
